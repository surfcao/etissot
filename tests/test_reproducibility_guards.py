class ProseNumbers(unittest.TestCase):
    """Every live-prose number is registered; results are recomputed."""

    TEXT = ('\\begin{document}\nThe median is 1.16 (Table 2), against 1.38 for an isotropic output.\n'
            '% an old copy: 1.26\n\\end{document}\n')

    def register(self, text):
        from etissot.validation.prose import tokens
        found = tokens(text)
        kinds = {'1.16': 'result', '1.38': 'result', '2': 'label'}
        entries = []
        for item in found:
            entry = dict(token=item['token'], anchor=item['anchor'], kind=kinds[item['token']])
            if entry['kind'] == 'result':
                entry['link'] = dict(refs=[dict(summary='s.json', path=['a' if item['token'] == '1.16' else 'b'])])
            entries.append(entry)
        return {'main.tex': entries}

    def test_changed_result_and_new_numbers_fail(self):
        from etissot.validation.prose import check
        values = {'a': 1.1604, 'b': 1.381}
        summary = lambda name: values
        register = self.register(self.TEXT)
        report = check({'main.tex': self.TEXT}, register, summary)
        self.assertEqual((report['results'], report['pinned']), (2, 1))
        edited = {'main.tex': self.TEXT.replace('1.16 (', '1.26 (')}
        with self.assertRaisesRegex(ValueError, 'Unregistered or changed'):
            check(edited, register, summary)
        # After the register is updated, the carried-over link still recomputes the value.
        import importlib.util
        spec = importlib.util.spec_from_file_location('update_prose_register', Path(__file__).resolve().parents[1] / 'scripts/update_prose_register.py')
        updater = importlib.util.module_from_spec(spec); spec.loader.exec_module(updater)
        from etissot.validation.prose import tokens
        carried, log = updater.align(tokens(edited['main.tex']), register['main.tex'])
        self.assertTrue(any(line.startswith('changed') for line in log))
        with self.assertRaisesRegex(ValueError, 'differs from regenerated'):
            check(edited, {'main.tex': carried}, summary)
        with self.assertRaisesRegex(ValueError, 'Unregistered or changed'):
            check({'main.tex': self.TEXT.replace('isotropic', 'isotropic 3-D')}, register, summary)
        extra = {'main.tex': register['main.tex'] + [dict(token='9', anchor='gone|gone', kind='design')]}
        with self.assertRaisesRegex(ValueError, 'no longer in'):
            check({'main.tex': self.TEXT}, extra, summary)

    def test_commented_copies_do_not_count(self):
        from etissot.validation.prose import tokens
        self.assertNotIn('1.26', [t['token'] for t in tokens(self.TEXT)])

    def test_bounds_and_stated_approximations(self):
        from etissot.validation.prose import agrees
        self.assertFalse(agrees(7.3, 1, 7.224))  # 7.224 is written 7.2 when rounded
        self.assertTrue(agrees(7.3, 1, 7.224, 'upper'))
        self.assertFalse(agrees(7.1, 1, 7.224, 'upper'))
        self.assertTrue(agrees(11, 0, 11.85, 'lower'))
        self.assertTrue(agrees(6, 0, 7.7e-7, 'below_power_of_ten'))
        self.assertFalse(agrees(7, 0, 7.7e-7, 'below_power_of_ten'))
        self.assertTrue(agrees(1720, 0, 1721.03, 'approx', 5))
        with self.assertRaises(ValueError):
            agrees(1720, 0, 1721.03, 'approx')


class BlocksAndTables(unittest.TestCase):
    def test_required_blocks_cannot_be_removed(self):
        with tempfile.TemporaryDirectory() as root:
            (Path(root) / 'tables').mkdir()
            (Path(root) / 'tables/a.tex').write_text('1')
            text = '% BEGIN GENERATED: a\n1\n% END GENERATED: a\n'
            compare_generated_blocks({'main.tex': text}, root, {'main.tex': ['a']})
            with self.assertRaisesRegex(ValueError, "missing \\['b'\\]"):
                compare_generated_blocks({'main.tex': text}, root, {'main.tex': ['a', 'b']})

    def test_every_table_environment_is_covered(self):
        from types import SimpleNamespace
        from etissot.validation.manuscript import check_tables, _normalized
        import hashlib
        analytic = '\\begin{table}\\label{tab:refs}\\begin{tabular}{l}x\\end{tabular}\\end{table}'
        contract = dict(analytic_tables={'tab:refs': hashlib.sha256(_normalized(analytic).encode()).hexdigest()})
        workspace = SimpleNamespace(output=Path('.'))
        self.assertEqual(check_tables({'main.tex': analytic}, workspace, contract)[0], 1)
        for text in ['\\begin{table*}\\begin{tabular}{l}1\\end{tabular}\\end{table*}',
                     analytic.replace('x', 'y'),
                     'loose \\begin{tabular}{l}1\\end{tabular}']:
            with self.subTest(text=text), self.assertRaises(ValueError):
                check_tables({'main.tex': text}, workspace, contract)


class StaleOutputs(unittest.TestCase):
    def test_failed_verification_replaces_an_earlier_pass(self):
        from etissot.validation.manuscript import verify
        with tempfile.TemporaryDirectory() as root:
            data, out = Path(root, 'data'), Path(root, 'out')
            (data / 'reference').mkdir(parents=True)
            workspace = Workspace(data, out).prepare(seed_reference=False)
            (out / 'manuscript_verification.json').write_text('{"status": "passed"}')
            with self.assertRaisesRegex(ValueError, 'No full reproduction'):
                verify(workspace, Path(root))
            self.assertEqual(json.loads((out / 'manuscript_verification.json').read_text())['status'], 'failed')

    def test_outputs_older_than_the_reproduction_are_refused(self):
        import os
        from etissot.validation.manuscript import freshness
        with tempfile.TemporaryDirectory() as root:
            workspace = Workspace(Path(root, 'data'), Path(root, 'out'))
            workspace.output.mkdir(parents=True)
            old = workspace.output / 'old.tex'
            old.write_text('x')
            os.utime(old, (1e9, 1e9))
            with self.assertRaisesRegex(ValueError, 'not written by the current reproduction'):
                freshness(workspace, 2e9)('old.tex')

    def test_output_may_not_overlap_the_manuscript(self):
        from etissot.cli import main
        with tempfile.TemporaryDirectory() as root:
            manuscript = Path(root, 'manuscript')
            manuscript.mkdir()
            with self.assertRaises(SystemExit):
                main(['reproduce', '--data', str(Path(root, 'data')), '--output', str(manuscript / 'out'),
                      '--manuscript', str(manuscript)])
