class SeededCopies(unittest.TestCase):
    def test_seeded_reference_copies_are_refused_until_regenerated(self):
        with tempfile.TemporaryDirectory() as root:
            data, out = Path(root, 'data'), Path(root, 'out')
            (data / 'reference/summaries').mkdir(parents=True)
            (data / 'reference/baselines').mkdir()
            (data / 'reference/summaries/geometry.json').write_text('{"a": 1}')
            (data / 'reference/baselines/radius_audit.json').write_text('{}')
            workspace = Workspace(data, out).prepare(seed_reference=True)
            self.assertEqual(workspace.seeded_copies(), ['summaries/geometry.json'])
            with self.assertRaises(ValueError):
                workspace.require_regenerated()
            (out / 'summaries/geometry.json').write_text('{"a": 2}')  # regenerated by an analysis
            self.assertEqual(workspace.seeded_copies(), [])
            workspace.require_regenerated()
            # Baselines are never recorded as seeded outputs.
            record = json.loads((out / '.seeded_reference.json').read_text())
            self.assertNotIn('baselines/radius_audit.json', record)

    def test_discard_removes_only_unmodified_seeded_copies(self):
        with tempfile.TemporaryDirectory() as root:
            data, out = Path(root, 'data'), Path(root, 'out')
            (data / 'reference/summaries').mkdir(parents=True)
            (data / 'reference/summaries/geometry.json').write_text('{"a": 1}')
            (data / 'reference/summaries/land.json').write_text('{"b": 1}')
            workspace = Workspace(data, out).prepare(seed_reference=True)
            (out / 'summaries/land.json').write_text('{"b": 2}')  # regenerated by an analysis
            self.assertEqual(workspace.discard_seeded_copies(), ['summaries/geometry.json'])
            self.assertFalse((out / 'summaries/geometry.json').exists())
            self.assertEqual((out / 'summaries/land.json').read_text(), '{"b": 2}')
            self.assertEqual(workspace.seeded_copies(), [])

    def test_check_refuses_missing_or_incomplete_run(self):
        from etissot.cli import main
        with tempfile.TemporaryDirectory() as root:
            data, out = Path(root, 'data'), Path(root, 'out')
            (data / 'reference').mkdir(parents=True)
            with self.assertRaises(SystemExit):
                main(['check', '--data', str(data), '--output', str(out)])
            (out / 'run_report.json').write_text(json.dumps([{'step': 'fit', 'status': 'failed'}]))
            with self.assertRaises(SystemExit):
                main(['check', '--data', str(data), '--output', str(out)])

    def test_reproduce_style_preparation_seeds_only_baselines(self):
        with tempfile.TemporaryDirectory() as root:
            data, out = Path(root, 'data'), Path(root, 'out')
            (data / 'reference/summaries').mkdir(parents=True)
            (data / 'reference/baselines').mkdir()
            (data / 'reference/summaries/geometry.json').write_text('{}')
            (data / 'reference/baselines/radius_audit.json').write_text('{}')
            Workspace(data, out).prepare(seed_reference=False)
            self.assertFalse((out / 'summaries/geometry.json').exists())
            self.assertTrue((out / 'baselines/radius_audit.json').exists())


class GeneratedBlocks(unittest.TestCase):
    def test_marker_with_unsupported_name_is_not_skipped(self):
        text = '% BEGIN GENERATED: bad-name\nx\n% END GENERATED: bad-name\n'
        with tempfile.TemporaryDirectory() as out:
            with self.assertRaises(ValueError):
                compare_generated_blocks({'main.tex': text}, out)

    def test_block_names_may_contain_digits_and_capitals(self):
        text = '% BEGIN GENERATED: Table2\nrow\n% END GENERATED: Table2\n'
        with tempfile.TemporaryDirectory() as out:
            Path(out, 'tables').mkdir()
            Path(out, 'tables/Table2.tex').write_text('row\n')
            self.assertEqual(compare_generated_blocks({'main.tex': text}, out), ['Table2'])


class ComputedProse(unittest.TestCase):
    def test_seam_sentence_follows_the_counts(self):
        counts = {'GeoCLIP': 0, 'CSP-iNat': 1, 'CSP-fMoW': 1, 'Climplicit': 1}
        randomized = {'CSP-iNat', 'CSP-fMoW', 'Climplicit'}
        self.assertEqual(seam_exclusion_sentences(counts, randomized, 24.0, 1.0),
                         'Fixed-grid centers lie beyond every probe radius from the antimeridian, so exclusions '
                         'arise only on the randomized grids, where they remove one disc each for CSP-iNat, '
                         'CSP-fMoW and Climplicit.')
        counts['CSP-fMoW'] = 2
        self.assertIn('two discs for CSP-fMoW', seam_exclusion_sentences(counts, randomized, 24.0, 1.0))
        with self.assertRaises(ValueError):
            seam_exclusion_sentences({'GeoCLIP': 1}, set(), 24.0, 1.0)
        with self.assertRaises(ValueError):
            seam_exclusion_sentences(counts, randomized, 0.5, 1.0)


